-- =====================================================================
-- Migration initiale : schéma de la base Roadmap
-- =====================================================================
-- Ce fichier décrit la base Supabase telle qu'elle existe aujourd'hui
-- (elle a d'abord été créée à la main dans le tableau de bord).
-- Il ne contient que la structure : aucune donnée de test.
-- Ordre : une table est toujours créée avant celles qui la référencent.
--   profiles → modules → sprints → features → comments
-- La sécurité au niveau des lignes (RLS) n'est pas activée pour l'instant.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. profiles : un profil par membre de l'équipe
-- ---------------------------------------------------------------------
-- L'id du profil est le même que celui du compte Supabase Auth (auth.users).
-- Si le compte est supprimé, son profil l'est aussi (ON DELETE CASCADE).
create table public.profiles (
  id         uuid        not null,
  firstname  text,
  lastname   text,
  email      text        not null,
  avatar_url text,
  role       text        not null default 'user',
  created_at timestamptz not null default now(),

  constraint profiles_pkey primary key (id),
  constraint profiles_email_key unique (email),
  constraint profiles_id_fkey foreign key (id) references auth.users (id) on delete cascade,
  constraint profiles_role_check check (role = any (array['user', 'admin']))
);


-- ---------------------------------------------------------------------
-- 2. modules : les grandes parties du produit (facturation, onboarding…)
-- ---------------------------------------------------------------------
-- L'id est généré automatiquement (identity). Deux modules ne peuvent pas
-- porter le même nom, et chacun a une couleur pour s'y retrouver.
create table public.modules (
  id          bigint generated by default as identity,
  name        text        not null,
  color       text        not null,
  description text,
  created_at  timestamptz not null default now(),

  constraint modules_pkey primary key (id),
  constraint modules_name_key unique (name)
);


-- ---------------------------------------------------------------------
-- 3. sprints : périodes d'une ou deux semaines de réalisation
-- ---------------------------------------------------------------------
-- Dates de début et de fin obligatoires, objectif facultatif,
-- statut limité à trois valeurs (planifié par défaut).
create table public.sprints (
  id         bigint generated by default as identity,
  goal       text,
  start_date date        not null,
  end_date   date        not null,
  status     text        not null default 'planned',
  created_at timestamptz not null default now(),

  constraint sprints_pkey primary key (id),
  constraint sprints_status_check check (status = any (array['planned', 'active', 'completed']))
);


-- ---------------------------------------------------------------------
-- 4. features : les idées de features, bugs et améliorations
-- ---------------------------------------------------------------------
-- Une feature appartient obligatoirement à un module. Le sprint et la personne
-- assignée sont facultatifs : une feature sans sprint est dans le backlog.
-- Les contraintes CHECK limitent statut, priorité, effort et impact
-- aux valeurs prévues par le modèle de données.
create table public.features (
  id          bigint generated by default as identity,
  created_at  timestamptz not null default now(),
  title       text        not null,
  description text,
  status      text        not null default 'backlog',
  priority    text        not null default 'medium',
  effort      text,
  impact      text        not null default 'medium',
  module_id   bigint      not null,
  sprint_id   bigint,
  assigned_to uuid,

  constraint features_pkey primary key (id),
  -- Pas de ON DELETE : on ne peut pas supprimer un module, un sprint
  -- ou un profil tant que des features y sont rattachées.
  constraint features_module_id_fkey foreign key (module_id) references public.modules (id),
  constraint features_sprint_id_fkey foreign key (sprint_id) references public.sprints (id),
  constraint features_assigned_to_fkey foreign key (assigned_to) references public.profiles (id),
  constraint features_status_check check (status = any (array['backlog', 'todo', 'in_progress', 'done', 'cancelled'])),
  constraint features_priority_check check (priority = any (array['critical', 'high', 'medium', 'low', 'nice_to_have'])),
  constraint features_effort_check check (effort = any (array['xs', 's', 'm', 'l', 'xl'])),
  constraint features_impact_check check (impact = any (array['low', 'medium', 'high']))
);


-- ---------------------------------------------------------------------
-- 5. comments : l'historique des discussions sur une feature
-- ---------------------------------------------------------------------
-- Chaque commentaire a un auteur (un profil) et une date automatique.
-- Supprimer une feature supprime ses commentaires (ON DELETE CASCADE).
create table public.comments (
  id         bigint generated by default as identity,
  created_at timestamptz not null default now(),
  content    text        not null,
  feature_id bigint      not null,
  author_id  uuid        not null,

  constraint comments_pkey primary key (id),
  constraint comments_feature_id_fkey foreign key (feature_id) references public.features (id) on delete cascade,
  constraint comments_author_id_fkey foreign key (author_id) references public.profiles (id)
);


-- ---------------------------------------------------------------------
-- 6. Création automatique du profil à l'inscription
-- ---------------------------------------------------------------------
-- Quand un compte est créé dans auth.users, cette fonction ajoute
-- la ligne correspondante dans public.profiles (avec son id et son email).
-- SECURITY DEFINER : elle s'exécute avec les droits de son créateur,
-- car le service d'authentification n'a pas le droit d'écrire dans profiles.
-- search_path vide : on écrit les noms complets (public.profiles) par sécurité.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$;

-- Le déclencheur appelle la fonction après chaque nouvel utilisateur.
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- ---------------------------------------------------------------------
-- 7. Droits des rôles utilisés par l'application
-- ---------------------------------------------------------------------
-- anon : visiteur non connecté ; authenticated : membre connecté.
-- Ce sont les droits présents aujourd'hui sur chaque table.
-- Sans RLS, ces droits s'appliquent à toutes les lignes.
grant select, insert, update, delete, truncate, references, trigger
  on table public.profiles, public.modules, public.sprints, public.features, public.comments
  to anon, authenticated;
